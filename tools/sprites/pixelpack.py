"""Pack the animals' source frames for the pixel editor (the Pixel Editor artifact).

Reads art/source/<name>/<strip>-0.png .. -N.png (+ stand.png) and writes js/v2pack.js: one horizontal strip per
animation, keyed art/source/<name>/<strip>.png, added to the editor's SPRITE_PACK, with V2_N giving each key's frame count
(the editor cuts a strip back into frames with it). Edits come back through the editor's Send (db collection `pixeled`) or
a downloaded strip, and pixelpull.py cuts them into the numbered frames again.

  python3 tools/sprites/pixelpack.py [out.js]      (default js/v2pack.js)
"""
import base64, io, os, re, sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
SRC = os.path.join(ROOT, "art", "source")


def strips():
    for name in sorted(os.listdir(SRC)):
        d = os.path.join(SRC, name)
        if not os.path.isdir(d): continue
        found = {}
        for f in os.listdir(d):
            m = re.fullmatch(r"([a-z]+)-(\d+)\.png", f)
            if m: found.setdefault(m[1], {})[int(m[2])] = f
        for strip, fr in sorted(found.items()):
            n = max(fr) + 1
            if sorted(fr) != list(range(n)): raise SystemExit(f"{name}/{strip}: frames {sorted(fr)} are not 0..{n-1}")
            yield name, strip, [os.path.join(d, fr[i]) for i in range(n)]
        if os.path.exists(os.path.join(d, "stand.png")): yield name, "stand", [os.path.join(d, "stand.png")]


def png_uri(im):
    b = io.BytesIO(); im.save(b, "PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(b.getvalue()).decode()


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "js", "v2pack.js")
    pack, counts = {}, {}
    for name, strip, files in strips():
        ims = [Image.open(f).convert("RGBA") for f in files]
        w, h = ims[0].size
        if any(i.size != (w, h) for i in ims): raise SystemExit(f"{name}/{strip}: frames differ in size")
        sheet = Image.new("RGBA", (w * len(ims), h))
        for i, im in enumerate(ims): sheet.paste(im, (i * w, 0))
        key = f"art/source/{name}/{strip}.png"
        pack[key], counts[key] = png_uri(sheet), len(ims)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    import json
    with open(out, "w") as f:
        f.write("// GENERATED by tools/sprites/pixelpack.py from art/source/**: do not edit. The animals' source frames, one strip per animation.\n")
        f.write("Object.assign(SPRITE_PACK, " + json.dumps(pack) + ");\n")
        f.write("const V2_N = " + json.dumps(counts) + ";\n")
    print(f"{len(pack)} strips -> {out} ({os.path.getsize(out)//1024} KB)")


main()
